def search(query="", region="CN", limit=20):
    query = (query or "").strip().lower()
    region = (region or "CN").strip().upper()
    results = []
    for merchant in CHINA_MERCHANTS:
        if region and region != "ALL" and merchant["region"] != region:
            continue
        haystack = " ".join(
            [
                merchant["merchant_id"],
                merchant["name"],
                merchant["category"],
                merchant["description"],
            ]
            + merchant["aliases"]
        ).lower()
        if query and query not in haystack:
            continue
        results.append(dict(merchant))
    return results[:limit]


def get(merchant_id):
    for merchant in CHINA_MERCHANTS:
        if merchant["merchant_id"] == merchant_id:
            return dict(merchant)
    return None
